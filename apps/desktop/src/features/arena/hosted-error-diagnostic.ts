// A presentation allowlist, not a wire-schema restriction. New server codes remain
// recoverable/exportable, but never become user-facing text until reviewed here.
const publicDiagnosticCodes = new Set([
  'UNAUTHORIZED', 'FORBIDDEN', 'NOT_FOUND', 'RATE_LIMITED', 'INVALID_REQUEST', 'INVALID_JSON', 'METHOD_NOT_ALLOWED',
  'INVALID_GENERATION_REQUEST_ID', 'ARENA_REQUEST_TOO_LARGE',
  'ARENA_PROVIDER_UNAVAILABLE', 'ARENA_PROVIDER_UNKNOWN', 'ARENA_MODEL_UNKNOWN', 'ARENA_PROVIDER_KEY_EMPTY',
  'ARENA_COMPANION_PROTOCOL_UNSUPPORTED', 'ARENA_COMPANION_METADATA_UNAVAILABLE', 'ARENA_COMPANION_RESPONSE_TOO_LARGE',
  'ARENA_COMPANION_DELIVERY_FAILED', 'ARENA_COMPANION_PROJECTION_FAILED', 'ARENA_COMPANION_SERVICE_UNAVAILABLE',
  'ARENA_COMPANION_REPORT_ONLY_REQUIRED', 'ARENA_RECONCILIATION_PROTOCOL_UNSUPPORTED', 'ARENA_RECONCILIATION_INVALID_REQUEST',
  'ARENA_STRUCTURED_REPORT_INVALID', 'ARENA_CONTENT_POLICY_REJECTED', 'ARENA_PROMPT_BUDGET_EXCEEDED', 'ARENA_GENERATION_SERVICE_UNAVAILABLE',
  'AI_OUTPUT_TRUNCATED', 'AI_STREAM_INCOMPLETE', 'AI_UPSTREAM_REQUEST_FAILED', 'AI_UPSTREAM_TIMEOUT',
  'GENERATION_STREAM_FAILED', 'GENERATION_INCOMPLETE', 'GENERATION_FAILED', 'EMPTY_STREAM_OUTPUT',
]);

/** A code-shaped value can still contain an account, request ID or credential. */
export const sanitizeArenaHostedErrorCode = (value: unknown): string | null =>
  typeof value === 'string' && value.length > 0
    ? publicDiagnosticCodes.has(value) ? value : 'UNRECOGNIZED_ERROR'
    : null;
